'use strict';
// @firstflip/node — official Node.js client for the FirstFlip API (openapi.yaml in this repo).
// Zero dependencies; Node 18+ (global fetch, crypto.randomUUID).

const crypto = require('node:crypto');

const DEFAULT_BASE_URL = 'https://api.firstflip.ng/v1';
const VERSION = require('../package.json').version;
const RETRYABLE_CODES = new Set(['idempotency_in_progress', 'rate_limited', 'rate_unavailable', 'service_unavailable', 'internal_error']);

class FirstFlipError extends Error {
  constructor({ status, type, code, message, param, headers }) {
    super(message || 'FirstFlip API error');
    this.name = 'FirstFlipError';
    this.status = status;       // HTTP status, or undefined for a network error
    this.type = type;           // invalid_request_error | authentication_error | idempotency_error | rate_limit_error | api_error | connection_error
    this.code = code;           // stable machine-readable code — branch on this
    this.param = param || null;
    this.headers = headers || {};
  }
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

class FirstFlip {
  /**
   * @param {string} secretKey  ffk_test_… or ffk_live_… — server-side only.
   * @param {{ baseUrl?: string, timeoutMs?: number, maxRetries?: number, fetch?: typeof fetch }} [options]
   */
  constructor(secretKey, options = {}) {
    if (typeof secretKey !== 'string' || !/^ffk_(test|live)_/.test(secretKey)) {
      throw new Error('FirstFlip: pass your secret key (ffk_test_… or ffk_live_…). Keep it on your server.');
    }
    this._key = secretKey;
    this.livemode = secretKey.startsWith('ffk_live_');
    this._baseUrl = (options.baseUrl || DEFAULT_BASE_URL).replace(/\/$/, '');
    this._timeoutMs = options.timeoutMs ?? 30_000;
    this._maxRetries = options.maxRetries ?? 2;
    this._fetch = options.fetch || globalThis.fetch;
    if (typeof this._fetch !== 'function') throw new Error('FirstFlip: global fetch is missing (Node 18+ required) — pass options.fetch');

    this.account = { retrieve: () => this._request('GET', '/account') };
    this.charges = {
      create: (params, opts = {}) => this._request('POST', '/charges', { body: params, idempotencyKey: opts.idempotencyKey }),
      retrieve: (id) => this._request('GET', `/charges/${encodeURIComponent(id)}`),
      list: (params = {}) => this._request('GET', '/charges', { query: params }),
      cancel: (id, opts = {}) => this._request('POST', `/charges/${encodeURIComponent(id)}/cancel`, { idempotencyKey: opts.idempotencyKey }),
      simulatePayment: (id, opts = {}) => this._request('POST', `/charges/${encodeURIComponent(id)}/simulate_payment`, { idempotencyKey: opts.idempotencyKey }),
      // for await (const charge of firstflip.charges.listAll({ status: 'paid' })) { … }
      listAll: (params = {}) => this._paginate('/charges', params),
    };
    this.paymentLinks = {
      create: (params, opts = {}) => this._request('POST', '/payment_links', { body: params, idempotencyKey: opts.idempotencyKey }),
      retrieve: (id) => this._request('GET', `/payment_links/${encodeURIComponent(id)}`),
      list: (params = {}) => this._request('GET', '/payment_links', { query: params }),
      listAll: (params = {}) => this._paginate('/payment_links', params),
      deactivate: (id, opts = {}) => this._request('POST', `/payment_links/${encodeURIComponent(id)}/deactivate`, { idempotencyKey: opts.idempotencyKey }),
    };
    this.subaccounts = {
      create: (params, opts = {}) => this._request('POST', '/subaccounts', { body: params, idempotencyKey: opts.idempotencyKey }),
      retrieve: (id) => this._request('GET', `/subaccounts/${encodeURIComponent(id)}`),
      list: (params = {}) => this._request('GET', '/subaccounts', { query: params }),
      listAll: (params = {}) => this._paginate('/subaccounts', params),
      suspend: (id, opts = {}) => this._request('POST', `/subaccounts/${encodeURIComponent(id)}/suspend`, { idempotencyKey: opts.idempotencyKey }),
      activate: (id, opts = {}) => this._request('POST', `/subaccounts/${encodeURIComponent(id)}/activate`, { idempotencyKey: opts.idempotencyKey }),
    };
    this.transfers = {
      create: (params, opts = {}) => this._request('POST', '/transfers', { body: params, idempotencyKey: opts.idempotencyKey }),
      retrieve: (id) => this._request('GET', `/transfers/${encodeURIComponent(id)}`),
      list: (params = {}) => this._request('GET', '/transfers', { query: params }),
      listAll: (params = {}) => this._paginate('/transfers', params),
      simulate: (id, status, opts = {}) => this._request('POST', `/transfers/${encodeURIComponent(id)}/simulate`, { body: { status }, idempotencyKey: opts.idempotencyKey }),
      // 1–50 payouts in one call; references are generated by FirstFlip as `<batch id>:<index>`.
      createBatch: (transfers, opts = {}) => this._request('POST', '/transfers/bulk', { body: { transfers }, idempotencyKey: opts.idempotencyKey }),
      retrieveBatch: (id) => this._request('GET', `/transfers/bulk/${encodeURIComponent(id)}`),
    };
    // FX quotes and trades (services sandbox: test mode only).
    this.fx = {
      createQuote: (params, opts = {}) => this._request('POST', '/fx/quotes', { body: params, idempotencyKey: opts.idempotencyKey }),
      retrieveQuote: (id) => this._request('GET', `/fx/quotes/${encodeURIComponent(id)}`),
      simulateQuote: (id, status, opts = {}) => this._request('POST', `/fx/quotes/${encodeURIComponent(id)}/simulate`, { body: { status }, idempotencyKey: opts.idempotencyKey }),
      createTrade: (params, opts = {}) => this._request('POST', '/fx/trades', { body: params, idempotencyKey: opts.idempotencyKey }),
      retrieveTrade: (id) => this._request('GET', `/fx/trades/${encodeURIComponent(id)}`),
      simulateTrade: (id, status, opts = {}) => this._request('POST', `/fx/trades/${encodeURIComponent(id)}/simulate`, { body: { status }, idempotencyKey: opts.idempotencyKey }),
    };
    this.virtualAccounts = {
      create: (params, opts = {}) => this._request('POST', '/virtual_accounts', { body: params, idempotencyKey: opts.idempotencyKey }),
      retrieve: (id) => this._request('GET', `/virtual_accounts/${encodeURIComponent(id)}`),
      // 1–50 static accounts in one call under one Idempotency-Key.
      createBatch: (accounts, opts = {}) => this._request('POST', '/virtual_accounts/bulk', { body: { accounts }, idempotencyKey: opts.idempotencyKey }),
      retrieveBatch: (id) => this._request('GET', `/virtual_accounts/bulk/${encodeURIComponent(id)}`),
      deactivate: (id, opts = {}) => this._request('POST', `/virtual_accounts/${encodeURIComponent(id)}/deactivate`, { idempotencyKey: opts.idempotencyKey }),
      simulatePayment: (id, params, opts = {}) => this._request('POST', `/virtual_accounts/${encodeURIComponent(id)}/simulate_payment`, { body: params, idempotencyKey: opts.idempotencyKey }),
    };
    // BVN verification: consent first, then simulate the provider outcome in test mode.
    this.verifications = {
      createBvn: (params, opts = {}) => this._request('POST', '/verifications/bvn', { body: params, idempotencyKey: opts.idempotencyKey }),
      retrieveBvn: (id) => this._request('GET', `/verifications/bvn/${encodeURIComponent(id)}`),
      simulateBvn: (id, outcome, opts = {}) => this._request('POST', `/verifications/bvn/${encodeURIComponent(id)}/simulate`, { body: { outcome }, idempotencyKey: opts.idempotencyKey }),
      // Resolve the account name before a payout, so a wrong number never carries money.
      resolveBank: (params, opts = {}) => this._request('POST', '/verifications/bank_account', { body: params, idempotencyKey: opts.idempotencyKey }),
    };
    // OTP as a service: your app sends and checks one-time codes through FirstFlip.
    this.otps = {
      pricing: () => this._request('GET', '/otps/pricing'),
      create: (params, opts = {}) => this._request('POST', '/otps', { body: params, idempotencyKey: opts.idempotencyKey }),
      retrieve: (id) => this._request('GET', `/otps/${encodeURIComponent(id)}`),
      validate: (id, otp, opts = {}) => this._request('POST', `/otps/${encodeURIComponent(id)}/validate`, { body: { otp }, idempotencyKey: opts.idempotencyKey }),
    };
    // Integration questions answered from the FirstFlip docs only (POST /v1/assistant). A question is
    // read-only and the route carries no idempotency middleware, so it is sent unkeyed; a retry only
    // asks again.
    this.assistant = { ask: (question) => this._request('POST', '/assistant', { body: { question }, unkeyed: true }) };
    // Virtual cards. `fund`, `withdraw` and `simulate_authorization` move a sandbox balance and record a
    // ledger row — they are not money, and every one of them is a keyed write. `freeze` and `close` take an
    // optional reason; sending none must send no body, so an omitted `params` stays undefined.
    this.cards = {
      create: (params, opts = {}) => this._request('POST', '/cards', { body: params, idempotencyKey: opts.idempotencyKey }),
      retrieve: (id) => this._request('GET', `/cards/${encodeURIComponent(id)}`),
      list: (params = {}) => this._request('GET', '/cards', { query: params }),
      // for await (const card of firstflip.cards.listAll({ limit: 100 })) { … }
      listAll: (params = {}) => this._paginate('/cards', params),
      listTransactions: (id, params = {}) => this._request('GET', `/cards/${encodeURIComponent(id)}/transactions`, { query: params }),
      fund: (id, params, opts = {}) => this._request('POST', `/cards/${encodeURIComponent(id)}/fund`, { body: params, idempotencyKey: opts.idempotencyKey }),
      withdraw: (id, params, opts = {}) => this._request('POST', `/cards/${encodeURIComponent(id)}/withdraw`, { body: params, idempotencyKey: opts.idempotencyKey }),
      freeze: (id, params, opts = {}) => this._request('POST', `/cards/${encodeURIComponent(id)}/freeze`, { body: params, idempotencyKey: opts.idempotencyKey }),
      unfreeze: (id, opts = {}) => this._request('POST', `/cards/${encodeURIComponent(id)}/unfreeze`, { idempotencyKey: opts.idempotencyKey }),
      close: (id, params, opts = {}) => this._request('POST', `/cards/${encodeURIComponent(id)}/close`, { body: params, idempotencyKey: opts.idempotencyKey }),
      updateSpendLimits: (id, params, opts = {}) => this._request('POST', `/cards/${encodeURIComponent(id)}/spend_limits`, { body: params, idempotencyKey: opts.idempotencyKey }),
      simulateAuthorization: (id, params, opts = {}) => this._request('POST', `/cards/${encodeURIComponent(id)}/simulate_authorization`, { body: params, idempotencyKey: opts.idempotencyKey }),
    };
    this.webhooks = { verify, constructEvent };
  }

  async* _paginate(path, params) {
    let startingAfter = params.starting_after;
    for (;;) {
      const page = await this._request('GET', path, { query: { ...params, starting_after: startingAfter } });
      for (const item of page.data) yield item;
      if (!page.has_more || !page.data.length) return;
      startingAfter = page.data[page.data.length - 1].id;
    }
  }

  async _request(method, path, { body, query, idempotencyKey, unkeyed = false } = {}) {
    const url = new URL(this._baseUrl + path);
    for (const [k, v] of Object.entries(query || {})) if (v !== undefined && v !== null) url.searchParams.set(k, String(v));
    const headers = {
      Authorization: `Bearer ${this._key}`,
      Accept: 'application/json',
      'User-Agent': `firstflip-node/${VERSION} node/${process.versions.node}`,
    };
    if (body !== undefined) headers['Content-Type'] = 'application/json';
    // One key for the whole operation, reused on every retry: a retry can never act twice.
    if (method === 'POST' && !unkeyed) headers['Idempotency-Key'] = idempotencyKey || crypto.randomUUID();
    const payload = body === undefined ? undefined : JSON.stringify(body);

    for (let attempt = 0; ; attempt++) {
      let res; let err;
      const controller = new AbortController();
      const timer = setTimeout(() => controller.abort(), this._timeoutMs);
      try {
        res = await this._fetch(url, { method, headers, body: payload, signal: controller.signal });
      } catch (e) {
        err = new FirstFlipError({ type: 'connection_error', code: e.name === 'AbortError' ? 'timeout' : 'network_error', message: `Could not reach FirstFlip: ${e.message}` });
      } finally {
        clearTimeout(timer);
      }

      if (res) {
        const text = await res.text();
        let json = null;
        try { json = text ? JSON.parse(text) : null; } catch { /* non-JSON (proxy error page) */ }
        const resHeaders = Object.fromEntries(res.headers.entries());
        if (res.ok) return json;
        const e = json && json.error ? json.error : {};
        err = new FirstFlipError({
          status: res.status, type: e.type || 'api_error', code: e.code || `http_${res.status}`,
          message: e.message || `HTTP ${res.status}`, param: e.param, headers: resHeaders,
        });
      }

      const retryable = err.type === 'connection_error' || RETRYABLE_CODES.has(err.code) || err.status >= 500 || err.status === 429;
      if (!retryable || attempt >= this._maxRetries) throw err;
      const retryAfter = Number(err.headers['retry-after']);
      const backoff = Number.isFinite(retryAfter) && retryAfter > 0
        ? Math.min(retryAfter * 1000, 60_000)
        : Math.min(500 * 2 ** attempt, 8_000) * (0.5 + Math.random() / 2);
      await sleep(backoff);
    }
  }
}

/**
 * Verify a webhook: `raw` must be the exact request body (string or Buffer), `header` the
 * FirstFlip-Signature header, `secret` your endpoint's whsec_… secret.
 */
function verify(raw, header, secret, { toleranceSeconds = 300, now = Math.floor(Date.now() / 1000) } = {}) {
  const body = Buffer.isBuffer(raw) ? raw.toString('utf8') : String(raw);
  const parts = Object.fromEntries(String(header || '').split(',').map((p) => { const i = p.indexOf('='); return [p.slice(0, i).trim(), p.slice(i + 1).trim()]; }));
  const t = Number(parts.t);
  if (!Number.isInteger(t) || !parts.v1 || Math.abs(now - t) > toleranceSeconds) return false;
  const expected = Buffer.from(crypto.createHmac('sha256', String(secret)).update(`${t}.${body}`).digest('hex'), 'hex');
  const given = Buffer.from(String(parts.v1), 'hex');
  return expected.length === given.length && crypto.timingSafeEqual(expected, given);
}

/** Verify, then parse. Throws FirstFlipError('invalid_signature') when the signature doesn't match. */
function constructEvent(raw, header, secret, options) {
  if (!verify(raw, header, secret, options)) {
    throw new FirstFlipError({ status: 400, type: 'invalid_request_error', code: 'invalid_signature', message: 'Webhook signature verification failed.' });
  }
  return JSON.parse(Buffer.isBuffer(raw) ? raw.toString('utf8') : String(raw));
}

